export function setLang(l: Lang) {
  current = l;
  document.documentElement.lang = l;
}

export function getLang(): Lang {
  return current;
}

export function t(s: string): string {
  return current === "fr" ? fr[s] ?? s : s;
}

export function nameOf(x: { name: string; nameFr?: string }): string {
  return current === "fr" && x.nameFr ? x.nameFr : x.name;
}
